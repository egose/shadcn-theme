#!/usr/bin/env node
// ANGEX-07: generate the standard example's package-alias contract from the
// package source of truth (`packages/angular/publishable-projects.json`).
//
// Source integration model: normal development resolves
// `@egose/shadcn-theme-ng/*` through TypeScript path aliases that point at
// package *source* (`projects/*/src/public-api.ts`). This never validates
// built npm exports or plain versus `-tw` behavior; exact-tarball claims come
// only from `pnpm verify:consumers --release-dir release` (see
// `packages/angular/test/isolated-consumers.mjs`).
//
// This script is the single writer for:
//   1. the `paths` block in `@examples/standard/tsconfig.json`, and
//   2. `@examples/standard/src/app/example-subpaths.generated.ts`, which the
//      `consumer-boundary.spec.ts` suite statically imports to prove every
//      public subpath (including `menu`) resolves in source mode.
//
// Run: `pnpm --dir packages/angular/@examples/standard sync:aliases`
// Freshness is enforced by `packages/angular/test/example-consumer-boundary.test.mjs`.

import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const exampleDirectory = path.resolve(scriptDirectory, '..');
const workspaceDirectory = path.resolve(exampleDirectory, '../..');

export const PLAIN_PACKAGE = '@egose/shadcn-theme-ng';

export async function readSourceOfTruth(workspaceDir = workspaceDirectory) {
  const manifestPath = path.join(workspaceDir, 'publishable-projects.json');
  const projects = JSON.parse(await readFile(manifestPath, 'utf8'));
  if (!Array.isArray(projects) || projects.length === 0) {
    throw new Error('publishable-projects.json must be a non-empty array of project names');
  }
  const unique = new Set(projects);
  if (unique.size !== projects.length) throw new Error('publishable-projects.json contains duplicate project names');
  const sorted = [...projects].sort();
  if (projects.some((name, index) => name !== sorted[index])) {
    throw new Error('publishable-projects.json must be sorted');
  }
  for (const project of projects) {
    if (!existsSync(path.join(workspaceDir, 'projects', project, 'src', 'public-api.ts'))) {
      throw new Error(`Source project ${project} is missing projects/${project}/src/public-api.ts`);
    }
  }
  return projects;
}

export function aliasTarget(project) {
  return `../../projects/${project}/src/public-api.ts`;
}

export function renderPathsBlock(projects) {
  const lines = ['"paths": {'];
  for (const project of projects) {
    lines.push(`      "${PLAIN_PACKAGE}/${project}": ["${aliasTarget(project)}"],`);
  }
  // Strip the trailing comma from the final entry to match the file style.
  lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');
  lines.push('    }');
  return lines.join('\n');
}

const RESERVED_IDENTIFIERS = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete',
  'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function',
  'if', 'implements', 'import', 'in', 'instanceof', 'interface', 'let', 'new',
  'null', 'package', 'private', 'protected', 'public', 'return', 'super', 'switch',
  'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield',
]);

export function toIdentifier(project) {
  const base = project.replace(/(^|-)([a-z0-9])/g, (_, _dash, letter) => letter.toUpperCase()).replace(/^([A-Z])/, (letter) => letter.toLowerCase());
  return RESERVED_IDENTIFIERS.has(base) ? `${base}Lib` : base;
}

export function renderGeneratedModule(projects) {
  const lines = [
    '// GENERATED by scripts/sync-example-aliases.mjs — do not edit by hand.',
    '// Complete public subpath set for source-mode integration. Source of truth:',
    '// packages/angular/publishable-projects.json. Refresh with `pnpm sync:aliases`.',
    '// Statically imported by consumer-boundary.spec.ts so a missing or stale',
    '// alias fails the example build/test compile instead of hiding at runtime.',
  ];
  for (const project of projects) {
    lines.push(`import * as ${toIdentifier(project)} from '${PLAIN_PACKAGE}/${project}';`);
  }
  lines.push('');
  lines.push('export const EXAMPLE_PUBLIC_SUBPATHS = [');
  for (const project of projects) {
    lines.push(`  '${project}',`);
  }
  lines.push('] as const;');
  lines.push('');
  lines.push('export type ExamplePublicSubpath = (typeof EXAMPLE_PUBLIC_SUBPATHS)[number];');
  lines.push('');
  lines.push('export const EXAMPLE_PUBLIC_MODULES: Record<ExamplePublicSubpath, Record<string, unknown>> = {');
  for (const project of projects) {
    // Match prettier `quoteProps: as-needed` so the generated file is stable
    // under formatting: only quote keys that are not valid IdentifierNames.
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(project) ? project : `'${project}'`;
    lines.push(`  ${key}: ${toIdentifier(project)} as unknown as Record<string, unknown>,`);
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

function replacePathsBlock(tsconfigSource, pathsBlock) {
  const anchor = '"paths": {';
  const start = tsconfigSource.indexOf(anchor);
  if (start === -1) throw new Error('tsconfig.json has no "paths" block to synchronize');
  let depth = 0;
  let end = -1;
  for (let index = start; index < tsconfigSource.length; index++) {
    if (tsconfigSource[index] === '{') depth += 1;
    if (tsconfigSource[index] === '}') {
      depth -= 1;
      if (depth === 0) {
        end = index + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error('tsconfig.json "paths" block is unbalanced');
  return `${tsconfigSource.slice(0, start)}${pathsBlock}${tsconfigSource.slice(end)}`;
}

export async function syncExampleAliases({
  workspaceDir = workspaceDirectory,
  exampleDir = exampleDirectory,
} = {}) {
  const projects = await readSourceOfTruth(workspaceDir);
  const tsconfigPath = path.join(exampleDir, 'tsconfig.json');
  const tsconfigSource = await readFile(tsconfigPath, 'utf8');
  const updated = replacePathsBlock(tsconfigSource, renderPathsBlock(projects));
  if (updated !== tsconfigSource) await writeFile(tsconfigPath, updated, 'utf8');

  const generatedPath = path.join(exampleDir, 'src', 'app', 'example-subpaths.generated.ts');
  const generatedSource = renderGeneratedModule(projects);
  const previous = existsSync(generatedPath) ? await readFile(generatedPath, 'utf8') : null;
  if (previous !== generatedSource) await writeFile(generatedPath, generatedSource, 'utf8');
  return { projects: projects.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await syncExampleAliases();
    console.log(`Synchronized ${result.projects} example source aliases from publishable-projects.json`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
